CREATE TABLE IF NOT EXISTS gold.correlations (
    correlation_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id                VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    metric_x                  VARCHAR(32) NOT NULL REFERENCES bronze.measurement_definitions(noaa_code),
    metric_y                  VARCHAR(32) NOT NULL REFERENCES bronze.measurement_definitions(noaa_code),
    method                    VARCHAR(12) NOT NULL DEFAULT 'pearson',
    date_start_hst            DATE NOT NULL,
    date_end_hst              DATE NOT NULL,
    paired_sample_count       INTEGER NOT NULL CHECK (paired_sample_count >= 0),
    coefficient               DOUBLE PRECISION,
    processing_run_id         BIGINT REFERENCES gold.processing_runs(processing_run_id),
    computed_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (method IN ('pearson','spearman')),
    CHECK (date_start_hst <= date_end_hst),
    CHECK (coefficient IS NULL OR coefficient BETWEEN -1 AND 1),
    CHECK (metric_x < metric_y),
    UNIQUE (station_id, metric_x, metric_y, method, date_start_hst, date_end_hst)
);

