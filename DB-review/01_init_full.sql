-- ============================================================================
-- WAIMEA WAVECAST | PostgreSQL 17 / Google Cloud SQL
-- NOAA/NDBC STATION 51201 ONLY
-- Version: 2.0 (NOAA-only, GCS + evaluation schema)
-- Execute in database: waimea_wavecast using a role that owns the schemas or
-- has CREATE privilege in bronze, silver and gold (for example waimea_app).
-- Additive and rerunnable: no DROP DATABASE/SCHEMA/TABLE, no TRUNCATE.
-- No superuser-only extensions or Google Cloud-specific dependencies.
-- All observation instants are TIMESTAMPTZ (store in UTC); Hawaii dates use
-- timezone 'Pacific/Honolulu' in queries/ETL. No fake data is inserted.
-- ============================================================================
BEGIN;

CREATE SCHEMA IF NOT EXISTS bronze;
CREATE SCHEMA IF NOT EXISTS silver;
CREATE SCHEMA IF NOT EXISTS gold;

-- ============================ BRONZE =========================================
-- Reference metadata: not a second source of wave observations.
CREATE TABLE IF NOT EXISTS bronze.stations (
    station_id                VARCHAR(12) PRIMARY KEY,
    station_name              TEXT NOT NULL,
    location_name             TEXT NOT NULL,
    provider_name             TEXT NOT NULL DEFAULT 'NOAA NDBC',
    provider_url              TEXT NOT NULL,
    latitude                  NUMERIC(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude                 NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    local_timezone            TEXT NOT NULL DEFAULT 'Pacific/Honolulu',
    expected_interval_min     INTEGER CHECK (expected_interval_min > 0),
    measurement_start_date    DATE,
    measurement_end_date      DATE,
    active                    BOOLEAN NOT NULL DEFAULT TRUE,
    notes                     TEXT,
    metadata                  JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Canonical mapping of the 14 measurement fields in the user's NOAA notebook.
CREATE TABLE IF NOT EXISTS bronze.measurement_definitions (
    noaa_code                  VARCHAR(12) PRIMARY KEY,
    silver_column             TEXT NOT NULL UNIQUE,
    display_name              TEXT NOT NULL,
    meaning                   TEXT NOT NULL,
    unit                      TEXT NOT NULL,
    missing_codes             JSONB NOT NULL DEFAULT '[]'::jsonb,
    is_wave_feature           BOOLEAN NOT NULL DEFAULT FALSE,
    description               TEXT,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- annual/monthly/realtime are three feeds FROM THE SAME NOAA STATION.
CREATE TABLE IF NOT EXISTS bronze.source_feeds (
    feed_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id                VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    feed_key                  VARCHAR(32) NOT NULL,
    url_template              TEXT NOT NULL,
    source_format             VARCHAR(32) NOT NULL DEFAULT 'ndbc_stdmet_txt',
    data_priority             SMALLINT NOT NULL CHECK (data_priority BETWEEN 1 AND 100),
    poll_interval_minutes     INTEGER CHECK (poll_interval_minutes > 0),
    enabled                   BOOLEAN NOT NULL DEFAULT TRUE,
    notes                     TEXT,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (station_id, feed_key),
    CONSTRAINT chk_noaa_feed_key CHECK (feed_key IN ('historical_annual','historical_monthly','realtime'))
);

