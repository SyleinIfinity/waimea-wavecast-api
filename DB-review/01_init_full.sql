    scheduled_at              TIMESTAMPTZ,
    started_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at               TIMESTAMPTZ,
    status                    VARCHAR(16) NOT NULL DEFAULT 'running',
    request_url               TEXT,
    http_status               INTEGER CHECK (http_status BETWEEN 100 AND 599),
    response_time_ms          INTEGER CHECK (response_time_ms >= 0),
    received_rows             INTEGER NOT NULL DEFAULT 0 CHECK (received_rows >= 0),
    inserted_rows             INTEGER NOT NULL DEFAULT 0 CHECK (inserted_rows >= 0),
    revised_rows              INTEGER NOT NULL DEFAULT 0 CHECK (revised_rows >= 0),
    duplicate_rows            INTEGER NOT NULL DEFAULT 0 CHECK (duplicate_rows >= 0),
    rejected_rows             INTEGER NOT NULL DEFAULT 0 CHECK (rejected_rows >= 0),
    min_observed_at           TIMESTAMPTZ,
    max_observed_at           TIMESTAMPTZ,
    error_type                TEXT,
    error_message             TEXT,
    details                   JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT chk_ingestion_status CHECK (status IN ('running','success','partial','failed','skipped')),
    CONSTRAINT chk_ingestion_window CHECK (finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT chk_ingestion_observed_range CHECK (min_observed_at IS NULL OR max_observed_at IS NULL OR min_observed_at <= max_observed_at)
