-- Generic statistics for a physical metric on Hawaii calendar day/week/month.
CREATE TABLE IF NOT EXISTS gold.time_series_metrics (
    station_id                VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    period_type               VARCHAR(8) NOT NULL,
    period_start_hst          DATE NOT NULL,
    metric_code               VARCHAR(32) NOT NULL REFERENCES bronze.measurement_definitions(noaa_code),
    sample_count              INTEGER NOT NULL DEFAULT 0 CHECK (sample_count >= 0),
    valid_sample_count        INTEGER NOT NULL DEFAULT 0 CHECK (valid_sample_count >= 0),
    mean_value                DOUBLE PRECISION,
    median_value              DOUBLE PRECISION,
    min_value                 DOUBLE PRECISION,
    max_value                 DOUBLE PRECISION,
    stddev_value              DOUBLE PRECISION,
    p95_value                 DOUBLE PRECISION,
