-- One file/snapshot may be downloaded more than once; same hash = same bytes.
-- gcs_uri can be NULL during local notebook experiments, local_path can be NULL
-- after migration to Cloud Storage. At least one storage locator is required.
CREATE TABLE IF NOT EXISTS bronze.source_files (
    file_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id                VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    feed_id                   BIGINT NOT NULL REFERENCES bronze.source_feeds(feed_id),
    ingestion_run_id          BIGINT REFERENCES bronze.ingestion_runs(run_id) ON DELETE SET NULL,
    original_filename         TEXT NOT NULL,
    source_url                TEXT NOT NULL,
    storage_format            VARCHAR(16) NOT NULL,
    gcs_uri                   TEXT,
    local_path                TEXT,
    content_sha256            VARCHAR(64) NOT NULL,
    size_bytes                BIGINT CHECK (size_bytes >= 0),
    compression_type          VARCHAR(16) NOT NULL DEFAULT 'none',
    source_period_start       DATE,
    source_period_end         DATE,
    fetched_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    parsed_at                 TIMESTAMPTZ,
    parser_version            TEXT,
    columns_in_source         JSONB NOT NULL DEFAULT '[]'::jsonb,
    source_row_count          INTEGER CHECK (source_row_count >= 0),
    parse_error_count         INTEGER NOT NULL DEFAULT 0 CHECK (parse_error_count >= 0),
    parse_status              VARCHAR(16) NOT NULL DEFAULT 'pending',
    extra_metadata            JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT chk_file_hash CHECK (content_sha256 ~ '^[a-fA-F0-9]{64}$'),
    CONSTRAINT chk_file_location CHECK (gcs_uri IS NOT NULL OR local_path IS NOT NULL),
    CONSTRAINT chk_file_period CHECK (source_period_start IS NULL OR source_period_end IS NULL OR source_period_start <= source_period_end),
    CONSTRAINT chk_file_status CHECK (parse_status IN ('pending','parsed','partial','failed')),
    UNIQUE (station_id, feed_id, content_sha256)
);

-- Optional row-level raw archive for exact provenance, parse failures and replay.
-- Keep original .gz/.txt in GCS; JSONB and raw line are for traceability.
CREATE TABLE IF NOT EXISTS bronze.raw_observations (
    raw_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id                   BIGINT NOT NULL REFERENCES bronze.source_files(file_id),
    station_id                VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    source_line_number        INTEGER CHECK (source_line_number > 0),
    observed_at               TIMESTAMPTZ,
    raw_line                  TEXT,
    raw_values                JSONB NOT NULL DEFAULT '{}'::jsonb,
    row_sha256                VARCHAR(64) NOT NULL,
    parse_ok                  BOOLEAN NOT NULL DEFAULT TRUE,
    parse_error               TEXT,
    imported_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_raw_row_hash CHECK (row_sha256 ~ '^[a-fA-F0-9]{64}$'),
    CONSTRAINT chk_raw_row_payload CHECK (raw_line IS NOT NULL OR raw_values <> '{}'::jsonb),
    UNIQUE (file_id, row_sha256)
);

-- ============================ SILVER =========================================
-- Canonical normalized NOAA Standard Meteorological record. Missing value
-- sentinels (MM, 99, 999, 9999 etc) must be converted to SQL NULL by the ETL.
-- Pressure tendency and water level may be NEGATIVE.
CREATE TABLE IF NOT EXISTS silver.wave_observations (
    station_id                VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    observed_at               TIMESTAMPTZ NOT NULL,
    -- NOAA field mapping, EXACTLY the 14 measurements from the notebook:
    wind_direction_deg        DOUBLE PRECISION,  -- WDIR, deg true
    wind_speed_ms             DOUBLE PRECISION,  -- WSPD, m/s
    wind_gust_ms              DOUBLE PRECISION,  -- GST, m/s
    wave_height_m             DOUBLE PRECISION,  -- WVHT, m
    dominant_period_s         DOUBLE PRECISION,  -- DPD, s
    average_period_s          DOUBLE PRECISION,  -- APD, s
    mean_wave_direction_deg   DOUBLE PRECISION,  -- MWD, deg true
    sea_level_pressure_hpa    DOUBLE PRECISION,  -- PRES/BAR, hPa
    air_temperature_c         DOUBLE PRECISION,  -- ATMP, degC
    sea_surface_temp_c        DOUBLE PRECISION,  -- WTMP, degC
    dew_point_c               DOUBLE PRECISION,  -- DEWP, degC
    visibility_nmi            DOUBLE PRECISION,  -- VIS, nautical mile
    pressure_tendency_hpa     DOUBLE PRECISION,  -- PTDY, hPa over 3h
    tide_ft                   DOUBLE PRECISION,  -- TIDE, ft relative to MLLW
    -- Provenance and quality:
    source_kind               VARCHAR(24) NOT NULL,
    source_dataset            TEXT NOT NULL,
    source_file_id            BIGINT NOT NULL REFERENCES bronze.source_files(file_id),
    raw_id                    BIGINT REFERENCES bronze.raw_observations(raw_id),
    measurement_sha256        VARCHAR(64) NOT NULL,
    quality_status            VARCHAR(16) NOT NULL DEFAULT 'unverified',
    quality_flags             JSONB NOT NULL DEFAULT '{}'::jsonb,
    missing_fields            TEXT[] NOT NULL DEFAULT '{}'::text[],
    revision_no               INTEGER NOT NULL DEFAULT 1 CHECK (revision_no > 0),
    first_seen_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (station_id, observed_at),
    CONSTRAINT chk_obs_source_kind CHECK (source_kind IN ('historical_annual','historical_monthly','realtime')),
    CONSTRAINT chk_obs_quality CHECK (quality_status IN ('unverified','valid','partial','suspect','rejected')),
    CONSTRAINT chk_obs_hash CHECK (measurement_sha256 ~ '^[a-fA-F0-9]{64}$'),
    CONSTRAINT chk_wdir CHECK (wind_direction_deg IS NULL OR wind_direction_deg BETWEEN 0 AND 360),
    CONSTRAINT chk_mwd CHECK (mean_wave_direction_deg IS NULL OR mean_wave_direction_deg BETWEEN 0 AND 360),
    CONSTRAINT chk_wspd CHECK (wind_speed_ms IS NULL OR wind_speed_ms >= 0),
    CONSTRAINT chk_gust CHECK (wind_gust_ms IS NULL OR wind_gust_ms >= 0),
    CONSTRAINT chk_wave CHECK (wave_height_m IS NULL OR wave_height_m >= 0),
    CONSTRAINT chk_dpd CHECK (dominant_period_s IS NULL OR dominant_period_s > 0),
    CONSTRAINT chk_apd CHECK (average_period_s IS NULL OR average_period_s > 0),
    CONSTRAINT chk_pressure CHECK (sea_level_pressure_hpa IS NULL OR sea_level_pressure_hpa > 0),
    CONSTRAINT chk_visibility CHECK (visibility_nmi IS NULL OR visibility_nmi >= 0)
);

-- The current canonical record and every material change are tracked separately.
CREATE TABLE IF NOT EXISTS silver.wave_observation_revisions (
    revision_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id                VARCHAR(12) NOT NULL,
    observed_at               TIMESTAMPTZ NOT NULL,
    revision_no               INTEGER NOT NULL CHECK (revision_no > 0),
    source_kind               VARCHAR(24) NOT NULL,
    source_file_id            BIGINT NOT NULL REFERENCES bronze.source_files(file_id),
    raw_id                    BIGINT REFERENCES bronze.raw_observations(raw_id),
    measurement_sha256        VARCHAR(64) NOT NULL,
    change_type               VARCHAR(16) NOT NULL,
    snapshot                  JSONB NOT NULL,
    recorded_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (station_id, observed_at)
      REFERENCES silver.wave_observations(station_id, observed_at) ON DELETE RESTRICT,
    CONSTRAINT chk_revision_type CHECK (change_type IN ('initial','correction')),
    UNIQUE (station_id, observed_at, revision_no)
);

-- BEFORE UPDATE: archive has higher priority than realtime; prevent regression
-- from a previously QC'd archive to a fresh realtime download.
CREATE OR REPLACE FUNCTION silver.prepare_wave_observation_revision()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    old_priority INTEGER;
    new_priority INTEGER;
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.revision_no := 1;
        NEW.updated_at := now();
        RETURN NEW;
    END IF;

    old_priority := CASE OLD.source_kind
        WHEN 'historical_annual' THEN 3
        WHEN 'historical_monthly' THEN 2
        ELSE 1 END;
    new_priority := CASE NEW.source_kind
        WHEN 'historical_annual' THEN 3
        WHEN 'historical_monthly' THEN 2
        ELSE 1 END;

    IF new_priority < old_priority THEN
        -- Ignore an attempted downgrade. Bronze still records the source row.
        RETURN NULL;
    END IF;

    NEW.first_seen_at := OLD.first_seen_at;
    NEW.last_seen_at := now();
    IF ROW(NEW.measurement_sha256, NEW.source_kind, NEW.source_file_id,
           NEW.quality_status, NEW.quality_flags, NEW.missing_fields)
       IS DISTINCT FROM
       ROW(OLD.measurement_sha256, OLD.source_kind, OLD.source_file_id,
           OLD.quality_status, OLD.quality_flags, OLD.missing_fields) THEN
        NEW.revision_no := OLD.revision_no + 1;
        NEW.updated_at := now();
    ELSE
        NEW.revision_no := OLD.revision_no;
        NEW.updated_at := OLD.updated_at;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_wave_revision_prepare ON silver.wave_observations;
CREATE TRIGGER trg_wave_revision_prepare
BEFORE INSERT OR UPDATE ON silver.wave_observations
FOR EACH ROW EXECUTE FUNCTION silver.prepare_wave_observation_revision();

-- AFTER INSERT / UPDATE: keep an immutable JSONB snapshot of each revision.
CREATE OR REPLACE FUNCTION silver.audit_wave_observation_revision()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    revision_change VARCHAR(16);
BEGIN
    IF TG_OP = 'INSERT' THEN
        revision_change := 'initial';
    ELSE
        IF NEW.revision_no = OLD.revision_no THEN
            RETURN NEW;
        END IF;
        revision_change := 'correction';
    END IF;

    INSERT INTO silver.wave_observation_revisions
        (station_id, observed_at, revision_no, source_kind, source_file_id,
         raw_id, measurement_sha256, change_type, snapshot)
    VALUES
        (NEW.station_id, NEW.observed_at, NEW.revision_no, NEW.source_kind,
         NEW.source_file_id, NEW.raw_id, NEW.measurement_sha256,
         revision_change, to_jsonb(NEW))
    ON CONFLICT (station_id, observed_at, revision_no) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_wave_revision_audit ON silver.wave_observations;
CREATE TRIGGER trg_wave_revision_audit
AFTER INSERT OR UPDATE ON silver.wave_observations
FOR EACH ROW EXECUTE FUNCTION silver.audit_wave_observation_revision();

