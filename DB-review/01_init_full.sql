    CHECK (gap_start_at < gap_end_at),
    UNIQUE (station_id, gap_start_at, gap_end_at)
);

-- Calendar-day aggregates are computed in 'Pacific/Honolulu'. Never force
-- 48 expected samples if station's effective reporting interval differs.
CREATE TABLE IF NOT EXISTS silver.daily_wave_features (
    station_id                VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    date_hst                  DATE NOT NULL,
    sample_count              INTEGER NOT NULL DEFAULT 0 CHECK (sample_count >= 0),
    valid_wave_count          INTEGER NOT NULL DEFAULT 0 CHECK (valid_wave_count >= 0),
    expected_sample_count     INTEGER CHECK (expected_sample_count >= 0),
    coverage_ratio            DOUBLE PRECISION CHECK (coverage_ratio BETWEEN 0 AND 1),
    mean_wave_height_m        DOUBLE PRECISION,
    median_wave_height_m      DOUBLE PRECISION,
    max_wave_height_m         DOUBLE PRECISION,
    min_wave_height_m         DOUBLE PRECISION,
    p95_wave_height_m         DOUBLE PRECISION,
    stddev_wave_height_m      DOUBLE PRECISION,
    mean_dominant_period_s    DOUBLE PRECISION,
    circular_mean_direction_deg DOUBLE PRECISION,
    mean_sea_surface_temp_c   DOUBLE PRECISION,
    max_wind_speed_ms         DOUBLE PRECISION,
    good_quality_count        INTEGER NOT NULL DEFAULT 0 CHECK (good_quality_count >= 0),
    calculation_version       TEXT NOT NULL DEFAULT 'v1',
    calculated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (station_id, date_hst),
    CHECK (valid_wave_count <= sample_count),
    CHECK (good_quality_count <= sample_count),
    CHECK (circular_mean_direction_deg IS NULL OR circular_mean_direction_deg BETWEEN 0 AND 360)
);

