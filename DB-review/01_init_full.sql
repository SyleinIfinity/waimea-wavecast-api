-- NOAA timestamps may be irregular; estimated missing slots are heuristic only.
CREATE TABLE IF NOT EXISTS silver.observation_gaps (
    gap_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id                VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    gap_start_at              TIMESTAMPTZ NOT NULL,
    gap_end_at                TIMESTAMPTZ NOT NULL,
    assumed_interval_min      INTEGER CHECK (assumed_interval_min > 0),
    estimated_missing_slots   INTEGER CHECK (estimated_missing_slots >= 0),
