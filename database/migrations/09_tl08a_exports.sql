BEGIN;
CREATE TABLE IF NOT EXISTS gold.dataset_exports (
  export_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  layer TEXT NOT NULL CHECK (layer IN ('bronze','silver','gold')),
  partition_key TEXT NOT NULL,
  schema_version TEXT NOT NULL,
  content_sha256 CHAR(64) NOT NULL,
  row_count INTEGER NOT NULL CHECK (row_count>=0),
  min_observed_at TIMESTAMPTZ,
  max_observed_at TIMESTAMPTZ,
  source_watermark TIMESTAMPTZ,
  gcs_uri TEXT NOT NULL,
  gcs_generation BIGINT,
  processing_run_id TEXT,
  state TEXT NOT NULL DEFAULT 'PENDING_EXPORT' CHECK (state IN ('PENDING_EXPORT','EXPORTING','VERIFIED','RETRY_SCHEDULED','FAILED')),
  active BOOLEAN NOT NULL DEFAULT FALSE,
  attempt_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  verified_at TIMESTAMPTZ,
  UNIQUE(layer,partition_key,schema_version,content_sha256),
  CHECK (state <> 'VERIFIED' OR gcs_generation IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_dataset_exports_active ON gold.dataset_exports(layer,partition_key) WHERE active;
CREATE INDEX IF NOT EXISTS idx_dataset_exports_pending ON gold.dataset_exports(state,created_at) WHERE state <> 'VERIFIED';
CREATE TABLE IF NOT EXISTS bronze.historical_backfill_jobs (
  job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feed_key TEXT NOT NULL CHECK (feed_key IN ('historical_annual','historical_monthly')),
  source_url TEXT NOT NULL,
  source_period TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED','RUNNING','RAW_STORED','BRONZE_APPLIED','SILVER_APPLIED','QC_APPLIED','GOLD_APPLIED','VERIFIED','FAILED')),
  source_sha256 CHAR(64),
  source_etag TEXT,
  source_last_modified TEXT,
  source_content_length BIGINT,
  source_row_count INTEGER,
  last_checked_at TIMESTAMPTZ,
  last_verified_at TIMESTAMPTZ,
  gcs_uri TEXT,
  gcs_generation BIGINT,
  last_batch_offset INTEGER NOT NULL DEFAULT 0,
  last_exported_partition TEXT,
  lease_token UUID,
  retry_count INTEGER NOT NULL DEFAULT 0,
  lease_until TIMESTAMPTZ,
  error_stage TEXT,
  started_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(feed_key,source_url)
);
COMMIT;
