-- Additive forward-only forecast ledger. Experimental models remain DRAFT;
-- no Raw/Silver measurements or approved Gold predictions are overwritten.
BEGIN;

CREATE TABLE IF NOT EXISTS gold.forward_forecasts (
    forecast_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    model_id BIGINT NOT NULL REFERENCES gold.model_registry(model_id),
    model_version TEXT NOT NULL,
    horizon VARCHAR(8) NOT NULL CHECK (horizon IN ('30min','1d','7d')),
    target_kind VARCHAR(24) NOT NULL CHECK (target_kind IN ('instant_wvht','hst_day_median_wvht')),
    issued_at TIMESTAMPTZ NOT NULL,
    anchor_at TIMESTAMPTZ NOT NULL,
    anchor_date_hst DATE,
    target_at TIMESTAMPTZ NOT NULL,
    target_date_hst DATE,
    predicted_value DOUBLE PRECISION NOT NULL CHECK (predicted_value >= 0),
    features_snapshot JSONB NOT NULL,
    source_sha256 VARCHAR(64) NOT NULL CHECK (source_sha256 ~ '^[a-f0-9]{64}$'),
    quality_status VARCHAR(16) NOT NULL DEFAULT 'experimental'
        CHECK (quality_status = 'experimental'),
    gcs_uri TEXT,
    gcs_generation TEXT,
    gcs_sha256 VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_forward_model_anchor UNIQUE (model_id, anchor_at),
    CONSTRAINT chk_forward_times CHECK (anchor_at <= issued_at AND issued_at < target_at),
    CONSTRAINT chk_forward_target CHECK (
      (horizon='30min' AND target_kind='instant_wvht' AND anchor_date_hst IS NULL AND target_date_hst IS NULL)
      OR (horizon IN ('1d','7d') AND target_kind='hst_day_median_wvht'
          AND anchor_date_hst IS NOT NULL AND target_date_hst IS NOT NULL
          AND target_date_hst=anchor_date_hst + CASE WHEN horizon='1d' THEN 1 ELSE 7 END)),
    CONSTRAINT chk_forward_gcs CHECK (
      (gcs_uri IS NULL AND gcs_generation IS NULL AND gcs_sha256 IS NULL)
      OR (gcs_uri LIKE 'gs://waimea-noaa/predictions/forward/%'
          AND gcs_generation ~ '^[0-9]+$' AND gcs_sha256 ~ '^[a-f0-9]{64}$'))
);
CREATE INDEX IF NOT EXISTS ix_forward_target ON gold.forward_forecasts(target_at, forecast_id);
CREATE INDEX IF NOT EXISTS ix_forward_model_issued ON gold.forward_forecasts(model_id, issued_at DESC);

-- Corrected NOAA truth appends a new event. Forecast bytes never change.
CREATE TABLE IF NOT EXISTS gold.forward_evaluations (
    evaluation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forecast_id BIGINT NOT NULL REFERENCES gold.forward_forecasts(forecast_id),
    actual_value DOUBLE PRECISION NOT NULL CHECK (actual_value >= 0),
    absolute_error DOUBLE PRECISION NOT NULL CHECK (absolute_error >= 0),
    squared_error DOUBLE PRECISION NOT NULL CHECK (squared_error >= 0),
    persistence_absolute_error DOUBLE PRECISION NOT NULL CHECK (persistence_absolute_error >= 0),
    truth_sha256 VARCHAR(64) NOT NULL CHECK (truth_sha256 ~ '^[a-f0-9]{64}$'),
    truth_revision_no INTEGER,
    truth_as_of_at TIMESTAMPTZ NOT NULL,
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_forward_truth_version UNIQUE (forecast_id, truth_sha256)
);
CREATE INDEX IF NOT EXISTS ix_forward_eval_latest ON gold.forward_evaluations(forecast_id, evaluated_at DESC);

-- Only forward-issued forecasts with QC-validated truth enter this dataset.
-- A corrected truth supersedes the earlier evaluation without rewriting it.
CREATE OR REPLACE VIEW gold.forward_training_examples AS
SELECT f.forecast_id, f.station_id, f.model_id, f.model_version, f.horizon,
       f.issued_at, f.anchor_at, f.anchor_date_hst, f.target_at, f.target_date_hst,
       f.features_snapshot, f.source_sha256, f.predicted_value,
       e.actual_value, e.absolute_error, e.persistence_absolute_error,
       e.truth_sha256, e.truth_revision_no, e.truth_as_of_at, e.evaluated_at
FROM gold.forward_forecasts f
JOIN LATERAL (
    SELECT * FROM gold.forward_evaluations
    WHERE forecast_id=f.forecast_id
    ORDER BY evaluated_at DESC,evaluation_id DESC LIMIT 1
) e ON true
WHERE f.gcs_uri IS NOT NULL AND f.quality_status='experimental';

COMMIT;
