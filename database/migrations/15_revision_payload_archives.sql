-- Full historical revision snapshots live in immutable monthly GCS objects.
-- Keep revision keys, hashes, source references and correction history in SQL.
CREATE TABLE IF NOT EXISTS silver.revision_payload_archives (
    archive_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    year_utc INTEGER NOT NULL CHECK (year_utc BETWEEN 2000 AND 2100),
    month_utc INTEGER NOT NULL CHECK (month_utc BETWEEN 1 AND 12),
    row_count INTEGER NOT NULL CHECK (row_count > 0),
    content_sha256 CHAR(64) NOT NULL CHECK (content_sha256 ~ '^[a-f0-9]{64}$'),
    gcs_uri TEXT NOT NULL CHECK (gcs_uri LIKE 'gs://waimea-noaa/datasets/revisions/%'),
    gcs_generation BIGINT NOT NULL CHECK (gcs_generation > 0),
    archived_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (station_id, year_utc, month_utc, content_sha256)
);
CREATE INDEX IF NOT EXISTS idx_revision_payload_archives_month
ON silver.revision_payload_archives (station_id, year_utc, month_utc);
