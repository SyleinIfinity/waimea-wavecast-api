-- Additive, isolated forward-issued Calisthenics 1.5 shadow ledger.
-- These rows never enter gold.forward_training_examples or approved predictions.
BEGIN;
CREATE TABLE IF NOT EXISTS gold.calisthenics_shadow_forecasts (
    forecast_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id VARCHAR(12) NOT NULL REFERENCES bronze.stations(station_id),
    model_id BIGINT NOT NULL REFERENCES gold.model_registry(model_id),
    model_version TEXT NOT NULL,
    horizon VARCHAR(8) NOT NULL CHECK (horizon IN ('30min','1d','7d','30d')),
    target_kind VARCHAR(32) NOT NULL CHECK (target_kind IN
        ('instant_wvht','hst_day_median_wvht','next_30_hst_days_mean_wvht')),
    issued_at TIMESTAMPTZ NOT NULL,
    anchor_at TIMESTAMPTZ NOT NULL,
    anchor_date_hst DATE,
    target_at TIMESTAMPTZ NOT NULL,
    target_date_hst DATE,
    predicted_value DOUBLE PRECISION NOT NULL CHECK (predicted_value >= 0),
    features_snapshot JSONB NOT NULL,
    source_sha256 VARCHAR(64) NOT NULL CHECK (source_sha256 ~ '^[a-f0-9]{64}$'),
    gcs_uri TEXT,
    gcs_generation TEXT,
    gcs_sha256 VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (model_id,anchor_at),
    CHECK (anchor_at <= issued_at AND issued_at < target_at),
    CHECK ((horizon='30min' AND target_kind='instant_wvht'
            AND anchor_date_hst IS NULL AND target_date_hst IS NULL
            AND target_at-anchor_at=interval '90 minutes')
        OR (horizon IN ('1d','7d') AND target_kind='hst_day_median_wvht'
            AND anchor_date_hst IS NOT NULL AND target_date_hst=anchor_date_hst
                + CASE horizon WHEN '1d' THEN 1 ELSE 7 END)
        OR (horizon='30d' AND target_kind='next_30_hst_days_mean_wvht'
            AND anchor_date_hst IS NOT NULL AND target_date_hst=anchor_date_hst+30)),
    CHECK ((gcs_uri IS NULL AND gcs_generation IS NULL AND gcs_sha256 IS NULL)
        OR (gcs_uri LIKE 'gs://waimea-noaa/predictions/shadow/calisthenics-1.5/%'
            AND gcs_generation ~ '^[0-9]+$' AND gcs_sha256 ~ '^[a-f0-9]{64}$'))
);
CREATE INDEX IF NOT EXISTS ix_calisthenics_shadow_target
    ON gold.calisthenics_shadow_forecasts(target_at,forecast_id);

CREATE TABLE IF NOT EXISTS gold.calisthenics_shadow_evaluations (
    evaluation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forecast_id BIGINT NOT NULL REFERENCES gold.calisthenics_shadow_forecasts(forecast_id),
    actual_value DOUBLE PRECISION NOT NULL CHECK (actual_value >= 0),
    absolute_error DOUBLE PRECISION NOT NULL CHECK (absolute_error >= 0),
    squared_error DOUBLE PRECISION NOT NULL CHECK (squared_error >= 0),
    persistence_absolute_error DOUBLE PRECISION NOT NULL CHECK (persistence_absolute_error >= 0),
    truth_sha256 VARCHAR(64) NOT NULL CHECK (truth_sha256 ~ '^[a-f0-9]{64}$'),
    truth_as_of_at TIMESTAMPTZ NOT NULL,
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (forecast_id,truth_sha256)
);
CREATE INDEX IF NOT EXISTS ix_calisthenics_shadow_evaluation_latest
    ON gold.calisthenics_shadow_evaluations(forecast_id,evaluation_id DESC);
COMMIT;
